  static Iterable<String> citiesMatching(String query) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return const Iterable<String>.empty();
    return cities.where((city) => city.toLowerCase().contains(q));
  }

  static Iterable<String> statesMatching(String query) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return const Iterable<String>.empty();
    return states.where((state) => state.toLowerCase().contains(q));
  }
